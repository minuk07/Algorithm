WITH ECOLI_SIZE AS (
    SELECT ID, PERCENT_RANK() OVER (ORDER BY SIZE_OF_COLONY DESC) AS RNK
      FROM ECOLI_DATA
)
SELECT ID, 
    CASE
       WHEN RNK <= 0.25 THEN 'CRITICAL'
       WHEN RNK > 0.25 && RNK <= 0.5 THEN 'HIGH'
       WHEN RNK > 0.5 && RNK <= 0.75 THEN 'MEDIUM'
       ELSE 'LOW'
     END AS COLONY_NAME
  FROM ECOLI_SIZE
ORDER BY ID;