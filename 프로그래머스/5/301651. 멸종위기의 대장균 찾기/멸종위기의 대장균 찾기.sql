WITH RECURSIVE GEN AS(
    SELECT E1.ID, 1 AS GENERATION
      FROM ECOLI_DATA E1
     WHERE E1.PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT E2.ID, GEN.GENERATION + 1
      FROM ECOLI_DATA E2
      JOIN GEN
        ON GEN.ID = E2.PARENT_ID
)
SELECT COUNT(*) AS COUNT, GEN.GENERATION
  FROM GEN
 WHERE NOT EXISTS(
    SELECT *
      FROM ECOLI_DATA E
     WHERE GEN.ID = E.PARENT_ID
 )
GROUP BY GEN.GENERATION;